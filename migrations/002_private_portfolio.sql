CREATE TABLE IF NOT EXISTS sedes (
  id TEXT PRIMARY KEY,
  nombre VARCHAR(200) NOT NULL,
  ciudad VARCHAR(80) NOT NULL,
  direccion VARCHAR(200) NOT NULL,
  activa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS programas (
  id TEXT PRIMARY KEY,
  nombre VARCHAR(200) NOT NULL,
  codigo VARCHAR(20) NOT NULL UNIQUE,
  sede_id TEXT NOT NULL REFERENCES sedes(id)
);

CREATE TABLE IF NOT EXISTS instructores (
  id TEXT PRIMARY KEY,
  nombre VARCHAR(150) NOT NULL,
  documento VARCHAR(12) NOT NULL UNIQUE,
  vinculacion VARCHAR(20) NOT NULL CHECK (vinculacion IN ('De planta', 'Técnico', 'Transversal')),
  sede_id TEXT NOT NULL REFERENCES sedes(id),
  correo VARCHAR(150) NOT NULL
);

CREATE TABLE IF NOT EXISTS fichas (
  id TEXT PRIMARY KEY,
  numero VARCHAR(8) NOT NULL UNIQUE,
  programa_id TEXT NOT NULL REFERENCES programas(id),
  jornada VARCHAR(10) NOT NULL CHECK (jornada IN ('Diurna', 'Nocturna', 'Mixta')),
  trimestre_actual VARCHAR(20) NOT NULL,
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE NOT NULL,
  instructor_jefe_id TEXT NOT NULL REFERENCES instructores(id),
  CHECK (fecha_fin > fecha_inicio)
);

CREATE TABLE IF NOT EXISTS competencias (
  id TEXT PRIMARY KEY,
  codigo VARCHAR(20) NOT NULL UNIQUE,
  nombre VARCHAR(200) NOT NULL,
  trimestre VARCHAR(20) NOT NULL,
  instructor_id TEXT NOT NULL REFERENCES instructores(id),
  programa_id TEXT NOT NULL REFERENCES programas(id)
);

CREATE TABLE IF NOT EXISTS aprendices (
  id TEXT PRIMARY KEY,
  nombre VARCHAR(150) NOT NULL,
  documento VARCHAR(12) NOT NULL UNIQUE,
  correo VARCHAR(150) NOT NULL,
  ficha_id TEXT NOT NULL REFERENCES fichas(id)
);

CREATE TABLE IF NOT EXISTS usuarios (
  documento VARCHAR(12) PRIMARY KEY,
  rol VARCHAR(15) NOT NULL CHECK (rol IN ('aprendiz', 'instructor', 'administrador', 'coordinador')),
  nombre VARCHAR(150) NOT NULL,
  correo VARCHAR(150) NOT NULL UNIQUE,
  referencia_id TEXT,
  password_hash TEXT NOT NULL,
  intentos_fallidos SMALLINT NOT NULL DEFAULT 0,
  bloqueado_hasta TIMESTAMPTZ,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS tareas (
  id TEXT PRIMARY KEY,
  competencia_id TEXT NOT NULL REFERENCES competencias(id),
  titulo VARCHAR(200) NOT NULL,
  descripcion TEXT NOT NULL DEFAULT '',
  instrucciones TEXT NOT NULL DEFAULT '',
  fecha_limite DATE NOT NULL,
  hora_limite VARCHAR(5) NOT NULL DEFAULT '23:59',
  adjuntos TEXT NOT NULL DEFAULT '[]'
);

CREATE TABLE IF NOT EXISTS tarea_ficha (
  tarea_id TEXT NOT NULL REFERENCES tareas(id) ON DELETE CASCADE,
  ficha_id TEXT NOT NULL REFERENCES fichas(id) ON DELETE CASCADE,
  PRIMARY KEY (tarea_id, ficha_id)
);

CREATE TABLE IF NOT EXISTS entregas (
  id TEXT PRIMARY KEY,
  tarea_id TEXT NOT NULL REFERENCES tareas(id) ON DELETE CASCADE,
  aprendiz_id TEXT NOT NULL REFERENCES aprendices(id) ON DELETE CASCADE,
  archivo VARCHAR(255) NOT NULL,
  archivo_bytes BYTEA NOT NULL,
  tipo_archivo VARCHAR(150) NOT NULL,
  fecha_entrega TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  estado VARCHAR(12) NOT NULL CHECK (estado IN ('Entregado', 'Calificado')),
  con_retraso BOOLEAN NOT NULL DEFAULT FALSE,
  nota DECIMAL(2,1) CHECK (nota BETWEEN 0 AND 5),
  resultado VARCHAR(12) CHECK (resultado IN ('Aprobado', 'No Aprobado')),
  retroalimentacion TEXT,
  UNIQUE (tarea_id, aprendiz_id)
);

CREATE TABLE IF NOT EXISTS retroalimentaciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entrega_id TEXT NOT NULL REFERENCES entregas(id) ON DELETE CASCADE,
  fecha TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  nota DECIMAL(2,1) NOT NULL CHECK (nota BETWEEN 0 AND 5),
  resultado VARCHAR(12) NOT NULL CHECK (resultado IN ('Aprobado', 'No Aprobado')),
  comentario TEXT NOT NULL,
  instructor VARCHAR(150) NOT NULL
);

CREATE TABLE IF NOT EXISTS notificaciones (
  id TEXT PRIMARY KEY,
  documento_destino VARCHAR(12) NOT NULL REFERENCES usuarios(documento) ON DELETE CASCADE,
  titulo VARCHAR(200) NOT NULL,
  detalle TEXT NOT NULL,
  fecha TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  leida BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS reportes_riesgo (
  id TEXT PRIMARY KEY,
  aprendiz_id TEXT NOT NULL REFERENCES aprendices(id) ON DELETE CASCADE,
  nivel VARCHAR(10) NOT NULL CHECK (nivel IN ('Bajo', 'Medio', 'Alto')),
  observaciones TEXT NOT NULL,
  orientacion TEXT NOT NULL DEFAULT '',
  emitido_por VARCHAR(150) NOT NULL,
  instructor_id TEXT NOT NULL REFERENCES instructores(id),
  fecha TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS observaciones (
  id TEXT PRIMARY KEY,
  instructor_id TEXT NOT NULL REFERENCES instructores(id) ON DELETE CASCADE,
  trimestre VARCHAR(20) NOT NULL,
  comentario TEXT NOT NULL,
  fecha TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS materiales (
  id TEXT PRIMARY KEY,
  titulo VARCHAR(200) NOT NULL,
  tipo VARCHAR(20) NOT NULL,
  trimestre VARCHAR(20) NOT NULL,
  competencia_id TEXT NOT NULL REFERENCES competencias(id),
  visibilidad VARCHAR(40) NOT NULL CHECK (visibilidad IN ('Público', 'Privado (solo mi ficha)', 'Restringido (solo instructores)')),
  propietario_id TEXT NOT NULL REFERENCES instructores(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS material_fichas (
  material_id TEXT NOT NULL REFERENCES materiales(id) ON DELETE CASCADE,
  ficha_id TEXT NOT NULL REFERENCES fichas(id) ON DELETE CASCADE,
  PRIMARY KEY (material_id, ficha_id)
);

CREATE TABLE IF NOT EXISTS notas (
  id TEXT PRIMARY KEY,
  documento_propietario VARCHAR(12) NOT NULL REFERENCES usuarios(documento) ON DELETE CASCADE,
  titulo VARCHAR(200) NOT NULL,
  contenido TEXT NOT NULL,
  fecha TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS sesiones_auth (
  token_hash CHAR(64) PRIMARY KEY,
  documento VARCHAR(12) NOT NULL REFERENCES usuarios(documento) ON DELETE CASCADE,
  expira_en TIMESTAMPTZ NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_fichas_instructor ON fichas(instructor_jefe_id);
CREATE INDEX IF NOT EXISTS idx_competencias_instructor_programa ON competencias(instructor_id, programa_id);
CREATE INDEX IF NOT EXISTS idx_aprendices_ficha ON aprendices(ficha_id);
CREATE INDEX IF NOT EXISTS idx_tarea_ficha_ficha ON tarea_ficha(ficha_id);
CREATE INDEX IF NOT EXISTS idx_entregas_aprendiz ON entregas(aprendiz_id);
CREATE INDEX IF NOT EXISTS idx_notificaciones_destino ON notificaciones(documento_destino, leida);
CREATE INDEX IF NOT EXISTS idx_riesgos_instructor ON reportes_riesgo(instructor_id);
CREATE INDEX IF NOT EXISTS idx_materiales_propietario ON materiales(propietario_id);
CREATE INDEX IF NOT EXISTS idx_material_fichas_ficha ON material_fichas(ficha_id);
CREATE INDEX IF NOT EXISTS idx_sesiones_expira ON sesiones_auth(expira_en);
